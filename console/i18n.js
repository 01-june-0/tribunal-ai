const has=key=>Object.prototype.hasOwnProperty.call(EN,key);
function pick(){
  let lang=null;
  try{const q=new URLSearchParams(location.search).get('lang');
    if(q==='en'||q==='ko'){lang=q;try{localStorage.setItem('tribunal.lang',q);}catch(e){/* private window */}}
    else{try{lang=localStorage.getItem('tribunal.lang');}catch(e){/* blocked storage */}}}catch(e){/* no URL API */}
  if(lang!=='en'&&lang!=='ko')lang=/^ko\b/i.test(navigator.language||'')?'ko':'en';
  return lang;
}
const lang=pick();
function t(text,...args){
  const out=lang==='ko'||!has(text)?text:EN[text];
  return args.length?out.replace(/\{(\d+)\}/g,(m,i)=>i<args.length?String(args[i]):m):out;
}
// Static page text: every text node and the title / placeholder / aria-label attributes, matched by exact text.
function translatePage(root){
  if(lang==='ko'||!root)return;
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  for(let node=walker.nextNode();node;node=walker.nextNode()){
    const raw=node.nodeValue,key=raw.trim();
    if(key&&has(key))node.nodeValue=raw.replace(key,()=>EN[key]);
  }
  for(const el of root.querySelectorAll('[title],[placeholder],[aria-label]'))for(const attr of ['title','placeholder','aria-label']){
    const value=el.getAttribute(attr);
    if(value&&has(value))el.setAttribute(attr,EN[value]);
  }
}
